"""筛选配置: 股票池规则、因子权重、阈值、数据源选择.

所有"可调参数"集中在此, 便于后续用回测调优(不要把阈值散落在各处).
起步数值仅为经验先验, 应以历史回测结果为准再定稿.
"""

from __future__ import annotations

import os

# ---------------------------------------------------------------------------
# 数据源选择(可插拔): 环境变量优先, 否则用默认
#   ASHARE_PROVIDER = akshare | tushare
#   TUSHARE_TOKEN   = <你的token>  (仅 tushare 需要)
# ---------------------------------------------------------------------------
DEFAULT_PROVIDER = os.environ.get("ASHARE_PROVIDER", "akshare").strip().lower()
TUSHARE_TOKEN = os.environ.get("TUSHARE_TOKEN", "").strip()

# 每只票明细取数之间的休眠(秒), 防止被数据源限频
REQUEST_SLEEP = float(os.environ.get("ASHARE_SLEEP", "0.4"))
# 取数失败重试次数
MAX_RETRY = int(os.environ.get("ASHARE_RETRY", "3"))


# ---------------------------------------------------------------------------
# 第0层: 股票池(主板)机械过滤规则
# ---------------------------------------------------------------------------
# 只做A股主板: 沪 600/601/603/605 + 深 000/001/002(中小板已并入主板)
MAINBOARD_PREFIXES = ("600", "601", "603", "605", "000", "001", "002")
# 剔除: 创业板300/301, 科创板688, 北交所 8xx/4xx/920 —— 不在上面前缀即自动排除

MIN_LIST_YEARS = 3          # 上市满3年(要有足够财务历史)
MIN_MKTCAP_YI = 30.0        # 最小总市值(亿), 避开壳/流动性陷阱
MAX_MKTCAP_YI = None        # 上不封顶(拥挤度由因子层压)
EXCLUDE_ST = True           # 剔除 ST/*ST/退市


# ---------------------------------------------------------------------------
# 因子复合权重(四大类). 起步权重, 待回测调优.
#   总分 = wq*质量 + wv*价值 + wc*(-拥挤) + wm*动量
# ---------------------------------------------------------------------------
FACTOR_WEIGHTS = {
    "quality": 0.35,
    "value": 0.30,
    "crowding": 0.15,   # 注意: 拥挤度越低越好, 计算时取负向
    "momentum": 0.20,
}

# 行业中性化: 在同一行业内做 Z 分(去极值), 避免跨行业比 PE 无意义
INDUSTRY_NEUTRAL = True
WINSOR_QUANTILE = 0.02      # 双侧去极值分位

# 价值陷阱护栏: 复合分排名后, 强制要求最低质量分位与动量不为最差
VALUE_TRAP_GUARD = {
    "min_quality_pct": 0.40,   # 质量分位需 >= 40%(排"便宜的烂公司")
    "min_momentum_pct": 0.20,  # 动量分位需 >= 20%(排暴跌可能有雷的票)
}


# ---------------------------------------------------------------------------
# 明细阶段: 只对通过批量层+主题层的候选做重取数(每只多次网络请求)
# ---------------------------------------------------------------------------
DETAIL_LIMIT_DEFAULT = 300   # 明细阶段最多处理多少只(控制耗时)
MOMENTUM_LOOKBACK_DAYS = 300 # 拉多少日线用于 12-1 动量
REPORT_COUNT_MONTHS = 6      # 研报覆盖统计近几个月


# ---------------------------------------------------------------------------
# 磁盘缓存: 取到的数据落盘, 反复测试不再重复拉取(可显著提速)
#   ASHARE_CACHE=0 关闭缓存
# ---------------------------------------------------------------------------
USE_CACHE = os.environ.get("ASHARE_CACHE", "1").strip() != "0"
CACHE_DIR = os.environ.get("ASHARE_CACHE_DIR", "data/cache/ashare")
# 各类数据的缓存有效期(秒). 到期或 --refresh 时重新拉取.
CACHE_TTL = {
    "spot": 6 * 3600,          # 快照: 当日复用
    "industry": 30 * 86400,    # 行业分类: 极少变
    "financials": 24 * 3600,   # 财务: 季度更新, 一天足够
    "price": 24 * 3600,        # 日线
    "report": 24 * 3600,       # 研报覆盖
    "list": 7 * 86400,         # 股票列表
}


# ---------------------------------------------------------------------------
# 输出
# ---------------------------------------------------------------------------
OUTPUT_DIR = "reports"       # 结果写到 reports/十五五主板筛选-YYYYMMDD/
